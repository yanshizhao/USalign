inline void trace_back_gotoh(const std::string& seqx, const std::string& seqy,
    const GotohMatrix& m, std::string& seqxA, std::string& seqyA,
    const int xlen, const int ylen, std::vector<int>& invmap, const int invmap_only=1)
{
    const IntMatrix& JumpH = m.JumpH;
    const IntMatrix& JumpV = m.JumpV;
    const IntMatrix& P = m.P;
    int i;
    int j;
    int gaplen;
    std::string buf;

    if (invmap_only) for (j = 0; j < ylen; j++) invmap[j] = -1;
    if (invmap_only!=1) buf.resize(std::max(xlen,ylen)+1);

    i=xlen;
    j=ylen;
    while(i+j)
    {
        gaplen=0;
        if (P[i][j]>=4)
        {
            gaplen=JumpH[i][j];
            j-=gaplen;
            if (invmap_only==1) continue;
            buf.assign(&seqy[j],gaplen);
            seqyA=buf+seqyA;

            buf.assign(gaplen,'-');
            seqxA=buf+seqxA;
        }
        else if (P[i][j] % 4 >= 2)
        {
            gaplen=JumpV[i][j];
            i-=gaplen;
            if (invmap_only==1) continue;
            buf.assign(&seqx[i],gaplen);
            seqxA=buf+seqxA;

            buf.assign(gaplen,'-');
            seqyA=buf+seqyA;
        }
        else
        {
            if (i==0 && j!=0)
            {
                buf.assign(seqy.data(),j);
                seqyA=buf+seqyA;
                buf.assign(j,'-');
                seqxA=buf+seqxA;
                break;
            }
            if (i!=0 && j==0)
            {
                buf.assign(seqx.data(),i);
                seqxA=buf+seqxA;
                buf.assign(i,'-');
                seqyA=buf+seqyA;
                break;
            }
            i--;
            j--;
            if (invmap_only) invmap[j]=i;
            if (invmap_only!=1)
            {
                seqxA=seqx[i]+seqxA;
                seqyA=seqy[j]+seqyA;
            }
        }
    }
}


inline void trace_back_sw(const std::string& seqx, const std::string& seqy,
    const GotohMatrix& m, std::string& seqxA, std::string& seqyA,
    const int xlen, const int ylen, std::vector<int>& invmap, const int invmap_only=1)
{
    const IntMatrix& JumpH = m.JumpH;
    const IntMatrix& JumpV = m.JumpV;
    const IntMatrix& P = m.P;
    int i;
    int j;
    int gaplen;
    bool found_start_cell=false;
    std::string buf;

    if (invmap_only) for (j = 0; j < ylen; j++) invmap[j] = -1;
    if (invmap_only!=1) buf.resize(std::max(xlen,ylen)+1);

    i=xlen;
    j=ylen;
    for (i=xlen;i>=0;i--)
    {
        for (j=ylen;j>=0;j--)
        {
            if (P[i][j]!=0)
            {
                found_start_cell=true;
                break;
            }
        }
        if (found_start_cell) break;
    }

    // copy C terminal sequence
    if (invmap_only!=1)
    {
        buf.assign(ylen-j,'-');
        seqxA=buf;
        buf.assign(&seqx[i],xlen-i);
        seqxA+=buf;

        buf.assign(&seqy[j],ylen-j);
        seqyA+=buf;
        buf.assign(xlen-i,'-');
        seqyA+=buf;
    }

    if (i<0||j<0) return;

    // traceback aligned sequences
    while(P[i][j]!=0)
    {
        gaplen=0;
        if (P[i][j]>=4)
        {
            gaplen=JumpH[i][j];
            j-=gaplen;
            if (invmap_only==1) continue;
            buf.assign(&seqy[j],gaplen);
            seqyA=buf+seqyA;

            buf.assign(gaplen,'-');
            seqxA=buf+seqxA;
        }
        else if (P[i][j] % 4 >= 2)
        {
            gaplen=JumpV[i][j];
            i-=gaplen;
            if (invmap_only==1) continue;
            buf.assign(&seqx[i],gaplen);
            seqxA=buf+seqxA;

            buf.assign(gaplen,'-');
            seqyA=buf+seqyA;
        }
        else
        {
            i--;
            j--;
            if (invmap_only) invmap[j]=i;
            if (invmap_only!=1)
            {
                seqxA=seqx[i]+seqxA;
                seqyA=seqy[j]+seqyA;
            }
        }
    }
    // copy N terminal sequence
    if (invmap_only!=1)
    {
        buf.assign(j,'-');
        buf.append(seqx.data(),i);
        seqxA=buf+seqxA;

        buf.assign(seqy.data(),j);
        buf.append(i,'-');
        seqyA=buf+seqyA;
    }
}


